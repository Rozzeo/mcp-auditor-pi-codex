"""Render the Threat Atlas into a browsable MCP Threat Encyclopedia (HTML).

This is the *human face* of the knowledge base: the same `threats.yaml` that
drives the scanner, presented as an OWASP-style, research-cited reference. It is
generated by ``mcp-audit intel build-docs``. Its visual language comes from
`_theme` — the same cream paper and offset shadows as the dashboard and the
playground, rather than the private sixteen-colour palette this page used to
carry. Pure string templating — no external dependencies, fully offline, never
executes anything.

The four lifecycle phases are the book's chapters, so they get the tier banner
and a number: a reader who lands here from a finding needs to know *when* in a
server's life the threat bites before they read a word about it.
"""

from __future__ import annotations

import html
from typing import Any

from ._theme import ATMOSPHERE_HTML, page_head

_PHASE_ORDER = ["creation", "deployment", "operation", "maintenance"]
_PHASE_LABEL = {
    "creation": "Creation",
    "deployment": "Deployment",
    "operation": "Operation",
    "maintenance": "Maintenance",
}
# All-caps, technical-poetic: what actually happens to a server in this phase.
_PHASE_TAGLINE = {
    "creation": "Where the tool is written and the lie is planted",
    "deployment": "Where the server meets a client that already trusts it",
    "operation": "Where the agent acts on whatever it was told",
    "maintenance": "Where an update rewrites what you already approved",
}
_DETECT_LABEL = {"yes": "Static", "partial": "Partial", "no": "Runtime / out of scope"}

