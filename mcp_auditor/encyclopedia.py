def _esc(text: Any) -> str:
    return html.escape(str(text if text is not None else ""))


def _source_html(src: dict[str, Any]) -> str:
    if src.get("arxiv"):
        sec = f" §{_esc(src['section'])}" if src.get("section") else ""
        return (
            f'<a href="https://arxiv.org/abs/{_esc(src["arxiv"])}" target="_blank" rel="noopener">'
            f'{_esc(src.get("title") or "arXiv:" + str(src["arxiv"]))}</a>{sec}'
        )
    if src.get("type") == "cve" or src.get("id"):
        cid = src.get("id", "")
        name = f" ({_esc(src['name'])})" if src.get("name") else ""
        return (
            f'<a href="https://nvd.nist.gov/vuln/detail/{_esc(cid)}" target="_blank" rel="noopener">'
            f"{_esc(cid)}</a>{name}"
        )
    if src.get("section"):
        return f"§{_esc(src['section'])}"
    return _esc(src.get("title") or "source")


def _threat_card(threat: dict[str, Any], references: dict[str, dict]) -> str:
    sev = _esc(threat.get("severity", "info"))
    detect = threat.get("static_detectability", "no")
    rules = threat.get("rules", []) or []
    rules_html = (
        " ".join(f'<code class="rulechip">{_esc(r)}</code>' for r in rules)
        if rules
        else '<span class="gap">no rule yet — known gap</span>'
    )
    signals = "".join(f"<li>{_esc(s)}</li>" for s in threat.get("static_signals", []))
    mitigations = "".join(f"<li>{_esc(m)}</li>" for m in threat.get("mitigations", []))
    can_establish = "".join(
        f"<li>{_esc(item)}</li>" for item in threat.get("engine_can_establish", [])
    )
    cannot_establish = "".join(
        f"<li>{_esc(item)}</li>" for item in threat.get("engine_cannot_establish", [])
    )
    review_questions = "".join(
        f"<li>{_esc(item)}</li>" for item in threat.get("review_questions", [])
    )
    applies = ", ".join(str(item).replace("_", " ") for item in threat.get("applies_to", []))
    applicability = f"<span><b>Applies to:</b> {_esc(applies)}</span>" if applies else ""
    scenario = (
        f'<div class="lesson"><h4>Scenario</h4><p>{_esc(threat.get("scenario"))}</p></div>'
        if threat.get("scenario") else ""
    )
    evidence_boundary = ""
    if can_establish or cannot_establish:
        evidence_boundary = f"""
        <div class="lesson-grid">
          <div><h4>What the engine can establish</h4><ul>{can_establish or '<li>—</li>'}</ul></div>
          <div><h4>What it cannot establish</h4><ul>{cannot_establish or '<li>—</li>'}</ul></div>
        </div>"""
    reviewer = (
        f'<div class="lesson"><h4>Reviewer questions</h4><ol>{review_questions}</ol></div>'
        if review_questions else ""
    )
    examples = ""
    if threat.get("safe_example") or threat.get("risky_example"):
        examples = f"""
        <div class="examples">
          <div class="prompt good" data-tag="Safer pattern">{_esc(threat.get('safe_example', '—'))}</div>
          <div class="prompt bad" data-tag="Risky pattern">{_esc(threat.get('risky_example', '—'))}</div>
        </div>"""

    sources_rendered = []
    for src in threat.get("sources", []):
        s = dict(src)
        if s.get("ref") and s["ref"] in references:
            base = {k: v for k, v in references[s["ref"]].items() if k != "key"}
            base.update({k: v for k, v in s.items() if k != "ref"})
            s = base
        sources_rendered.append(_source_html(s))
    sources_html = " · ".join(sources_rendered)

    aliases = threat.get("aliases", [])
    aliases_html = (
        f'<div class="aliases">aka {_esc(", ".join(aliases))}</div>' if aliases else ""
    )

    return f"""
    <article class="block labelled threat sev-{sev} detect-{_esc(detect)}"
             data-label="{_esc(threat.get("id"))}">
      <header>
        <h3>{_esc(threat.get("name"))}</h3>
        <span class="chip {sev}">{sev}</span>
        <span class="badge detect">{_esc(_DETECT_LABEL.get(detect, detect))}</span>
      </header>
      {aliases_html}
      <p class="summary">{_esc(threat.get("summary"))}</p>
      <div class="meta">
        <span><b>Attacker:</b> {_esc(threat.get("attacker", "").replace("_", " "))}</span>
        <span><b>Lifecycle:</b> {_esc(threat.get("lifecycle", "").replace("_", " "))}</span>
        <span><b>Detected by:</b> {rules_html}</span>
        {applicability}
      </div>
      <details>
        <summary>Learn, verify &amp; mitigate</summary>
        {scenario}
        {evidence_boundary}
        {reviewer}
        {examples}
        <div class="cols">
          <div><h4>Static signals</h4><ul>{signals or "<li>—</li>"}</ul></div>
          <div><h4>Mitigations</h4><ul>{mitigations or "<li>—</li>"}</ul></div>
        </div>
      </details>
      <footer class="sources">Sources: {sources_html or "—"}</footer>
    </article>"""


def _phase_banner(phase: str, index: int, count: int) -> str:
    """The chapter break for one lifecycle phase.

    Numbered by position in the lifecycle rather than by how many phases
    happened to be non-empty, so `Operation` is always 03 no matter which Atlas
    version you are reading.
    """
    # tier / tier-2 / tier-3 cycle the accent across the chapter breaks.
    variant = ["", " tier-2", " tier-3"][index % 3]
    return f"""
<section class="tier{variant}">
  <div class="num">{index + 1:02d}</div>
  <div class="body">
    <span class="label">// Phase {index + 1:02d}</span>
    <h2>{_PHASE_LABEL[phase]} phase</h2>
    <p class="tagline">{_PHASE_TAGLINE[phase]}</p>
  </div>
  <div class="stripe">{count} threat{"s" if count != 1 else ""}</div>
</section>"""


def build_encyclopedia(atlas: dict[str, Any]) -> str:
    """Return a self-contained HTML string for the whole Atlas."""
    threats = atlas.get("threats", [])
    references = {r["key"]: r for r in atlas.get("references", []) if isinstance(r, dict) and "key" in r}
    version = _esc(atlas.get("version"))
    released = _esc(atlas.get("released"))

    by_phase: dict[str, list[dict]] = {p: [] for p in _PHASE_ORDER}
    for t in threats:
        by_phase.setdefault(t.get("phase_group", "operation"), []).append(t)

    n_static = sum(1 for t in threats if t.get("static_detectability") == "yes")
    n_partial = sum(1 for t in threats if t.get("static_detectability") == "partial")
    n_gap = sum(1 for t in threats if not t.get("rules"))

    sections = []
    for index, phase in enumerate(_PHASE_ORDER):
        items = by_phase.get(phase, [])
        if not items:
            continue
        cards = "".join(_threat_card(t, references) for t in items)
        sections.append(
            f'<section class="phase phase-{phase}">'
            f"{_phase_banner(phase, index, len(items))}"
            f'<div class="deck">{cards}</div></section>'
        )

    ref_lines = []
    for r in references.values():
        if r.get("arxiv"):
            ref_lines.append(
                f'<li><a href="https://arxiv.org/abs/{_esc(r["arxiv"])}" target="_blank" '
                f'rel="noopener">{_esc(r.get("title"))}</a> (arXiv:{_esc(r["arxiv"])})</li>'
            )

    return f"""<!DOCTYPE html>
<html lang="en">
{page_head(f"MCP Threat Encyclopedia · v{version}", _CSS)}
<body>
{ATMOSPHERE_HTML}
<div class="wrap">
<header class="masthead">
  <h1>MCP Threat<br>Encyclopedia</h1>
  <p class="subtitle">Definitions v{version} · released {released}</p>
  <p class="lede">The research-cited catalog behind <code>mcp-audit</code>. Every threat
  maps to a detection rule or an honest gap.</p>
  <div class="stats">
    <span>{len(threats)} threats</span>
    <span>{n_static} statically detectable</span>
    <span>{n_partial} partial</span>
    <span>{n_gap} known gaps</span>
  </div>
</header>
{''.join(sections)}
<hr class="rule">
<section class="block labelled refs" data-label="Sources">
  <h3>Primary sources</h3>
  <ul class="glyph">{''.join(ref_lines)}</ul>
</section>
<footer class="stamped">
  <div>
    <h2>Catalog complete</h2>
    <p class="meta">Generated from <code>threats.yaml</code> by
    <code>mcp-audit intel build-docs</code>.</p>
  </div>
  <div class="stamp">Definitions v{version}</div>
</footer>
</div>
</body>
</html>"""
